        end

        histogram(ax,vals,x_hist_edges, ...
            'Normalization','probability', ...
            'FaceColor',results(g).color, ...
            'EdgeColor',results(g).color, ...
            'FaceAlpha',0.18, ...
            'LineWidth',0.9, ...
            'DisplayName',results(g).label);
    end

    xlim(ax,[x_left_px x_right_px]);

    if t1 <= switch_start_min

        local_apply_temperature_ticks( ...
            ax,x_left_px,x_right_px,pre_left_C,pre_right_C,5);

        xlabelText = 'Temperature before switch (°C)';

    elseif t0 >= switch_end_min

        local_apply_temperature_ticks( ...
            ax,x_left_px,x_right_px,post_left_C,post_right_C,5);

        xlabelText = 'Temperature after switch (°C)';

    else

        xticks(ax,linspace(x_left_px,x_right_px,5));
        xticklabels(ax,compose('%.0f',linspace(x_left_px,x_right_px,5)));

        xlabelText = 'Physical X position (px; gradient transitioning)';
    end

    ylabel(ax,'Fraction');
    xlabel(ax,xlabelText);

    title(ax,sprintf('%d-%d min',t0,t1), ...
        'FontWeight','normal','FontSize',9);

    box(ax,'off');
    set(ax,'TickDir','out');

    if w == 1
        legend(ax,'Location','northwest','Box','off');
    end
end

