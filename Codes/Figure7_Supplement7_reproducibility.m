% Reduced repository-facing analysis containing only the tracking analyses
% used for the data-derived panels in Figure 7 and Supplement 7.
%
% GENERATED PANELS
% ----------------
% Figure 7B
%   Plate-mean physical X position across the 30-min gradient-switch assay,
%   shown as genotype mean +/- SEM across independent plates.
%
% Figure 7C
%   Individual wild-type trajectories.
%
% Figure 7D
%   Individual unc-17 cKO trajectories.
%
% Supplement 7A
%   Instantaneous animal-position histograms in consecutive 3-min windows.
%
% Supplement 7B
%   Individual eat-4 cKO trajectories.
