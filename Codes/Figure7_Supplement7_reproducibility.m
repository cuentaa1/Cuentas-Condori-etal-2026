function [X,Y,plate] = local_load_xy_plate(xFile,yFile,pFile,key)

    if ~isfile(xFile)
        error('File not found: %s',xFile);
    end

    if ~isfile(yFile)
        error('File not found: %s',yFile);
    end

    if ~isfile(pFile)
        error('File not found: %s',pFile);
    end

    SX = load(xFile);
    SY = load(yFile);
    SP = load(pFile);

    xCandidates = ["X_"+key,"X_"+lower(key),"X_data","X"];
    yCandidates = ["Y_"+key,"Y_"+lower(key),"Y_data","Y"];
    pCandidates = ["plate_"+key,"plate_"+lower(key), ...
        "plate_data","plate_id","plate","PlateID"];

    X = local_get_matrix(SX,xCandidates,"X");
    Y = local_get_matrix(SY,yCandidates,"Y");

    if ~isequal(size(X),size(Y))
        error('%s: X and Y matrices must have identical dimensions.',key);
    end

    plate = local_get_vector(SP,pCandidates,size(X,2),"plate");
end


function M = local_get_matrix(S,candidates,label)

    for i = 1:numel(candidates)

        nm = char(candidates(i));

        if isfield(S,nm)

            v = S.(nm);

            if isnumeric(v) && ismatrix(v)
                M = double(v);
                return
            end
        end
    end

    fn = fieldnames(S);
    possible = {};

    for i = 1:numel(fn)

        v = S.(fn{i});

        if isnumeric(v) && ismatrix(v) && ~isvector(v)
            possible{end+1} = fn{i}; %#ok<AGROW>
        end
    end

    if numel(possible) == 1
        M = double(S.(possible{1}));
        return
    end

    error('Could not uniquely identify %s matrix in MAT file.',label);
end


function v = local_get_vector(S,candidates,nTracks,label)

    for i = 1:numel(candidates)

        nm = char(candidates(i));

        if isfield(S,nm)

            q = S.(nm);

            if isvector(q) && numel(q) == nTracks
                v = q(:);
                return
            end
        end
    end

    fn = fieldnames(S);
    possible = {};

    for i = 1:numel(fn)

        q = S.(fn{i});

        if isvector(q) && numel(q) == nTracks
            possible{end+1} = fn{i}; %#ok<AGROW>
        end
    end

    if numel(possible) == 1
        v = S.(possible{1});
        v = v(:);
        return
    end

    error('Could not uniquely identify %s vector in MAT file.',label);
end


function local_apply_temperature_ticks( ...
    ax,xLeft,xRight,tempLeft,tempRight,nTicks)

    tickPos = linspace(xLeft,xRight,nTicks);
    tickTemp = linspace(tempLeft,tempRight,nTicks);

    xticks(ax,tickPos);
    xticklabels(ax,compose('%.1f',tickTemp));
end


function local_set_bottom_temperature_axis( ...
    ax,xLeft,xRight,tempLeft,tempRight,nTicks)

    tickPos = linspace(xLeft,xRight,nTicks);
    tickTemp = linspace(tempLeft,tempRight,nTicks);

    set(ax,'XTick',tickPos);
    set(ax,'XTickLabel',compose('%.1f',tickTemp));

    xlabel(ax,'Temperature after switch (°C)');
end


function axTop = local_add_top_temperature_axis( ...
    fig,axBase,xLeft,xRight,tempLeft,tempRight,nTicks)
% Add transparent top X axis carrying the pre-switch temperature labels.

    oldUnits = axBase.Units;
    axBase.Units = 'normalized';
    pos = axBase.Position;
    axBase.Units = oldUnits;

    tickPos = linspace(xLeft,xRight,nTicks);
    tickTemp = linspace(tempLeft,tempRight,nTicks);

    axTop = axes(fig, ...
        'Position',pos, ...
        'Color','none', ...
        'XAxisLocation','top', ...
        'YAxisLocation','right', ...
        'XLim',[xLeft xRight], ...
        'YLim',axBase.YLim, ...
        'XTick',tickPos, ...
        'XTickLabel',compose('%.1f',tickTemp), ...
        'YTick',[], ...
        'Box','off', ...
        'HitTest','off');

    xlabel(axTop,'Temperature before switch (°C)');

    axTop.YColor = 'none';
    axTop.XColor = [0 0 0];
end


function local_add_thermal_background( ...
    ax,xLeft,xRight,tStart,tSwitch,tComplete,tEnd,coldRGB,warmRGB)
% Draw a pale true-color representation of the thermal landscape.
%
% 0-15 min:
%   left = cold, right = warm
%
% 15-18 min:
%   pale transition band
%
% 18-30 min:
%   left = warm, right = cold

    n = 256;
    a = linspace(0,1,n)';

    preRow = (1-a).*coldRGB + a.*warmRGB;
    postRow = (1-a).*warmRGB + a.*coldRGB;

    preImage = permute(repmat(preRow,[1 1 2]),[3 1 2]);
    postImage = permute(repmat(postRow,[1 1 2]),[3 1 2]);

    preImage = cat(1,preImage,preImage);
    postImage = cat(1,postImage,postImage);

    image(ax, ...
        'XData',[xLeft xRight], ...
        'YData',[tStart tSwitch], ...
        'CData',preImage, ...
        'AlphaData',0.40, ...
        'HandleVisibility','off');

    patch(ax, ...
        [xLeft xRight xRight xLeft], ...
        [tSwitch tSwitch tComplete tComplete], ...
        [0.94 0.94 0.94], ...
        'FaceAlpha',0.75, ...
        'EdgeColor','none', ...
        'HandleVisibility','off');

    image(ax, ...
        'XData',[xLeft xRight], ...
        'YData',[tComplete tEnd], ...
        'CData',postImage, ...
        'AlphaData',0.40, ...
        'HandleVisibility','off');
end


function [globalStats,binStats] = ...
    local_position_statistics(D,genotypeOrder)

    D = D(isfinite(D.MeanX_px),:);

    D.Genotype = categorical( ...
        string(D.Genotype),genotypeOrder,genotypeOrder);

    timeOrder = unique(string(D.TimeBin),'stable');

    D.TimeBin = categorical( ...
        string(D.TimeBin),timeOrder,timeOrder);

    D.PlateUID = categorical(string(D.PlateUID));

    % Full model includes the genotype-by-time interaction.
    fullM = fitlme(D, ...
        'MeanX_px ~ Genotype*TimeBin + (1|PlateUID)', ...
        'FitMethod','ML');

    % Reduced model without interaction.
    additiveM = fitlme(D, ...
        'MeanX_px ~ Genotype + TimeBin + (1|PlateUID)', ...
        'FitMethod','ML');

    % Time-only model for overall genotype effect.
    timeOnlyM = fitlme(D, ...
        'MeanX_px ~ TimeBin + (1|PlateUID)', ...
        'FitMethod','ML');

    cmpInteraction = compare(additiveM,fullM);
    cmpGenotype = compare(timeOnlyM,additiveM);

    pInteraction = cmpInteraction.pValue(end);
    pGenotype = cmpGenotype.pValue(end);

    globalStats = table( ...
        ["Genotype_x_TimeBin";"Overall_Genotype"], ...
        [pInteraction;pGenotype], ...
        'VariableNames',{'Test','P'});

    % Planned pairwise comparisons within each time bin.
    Bin = strings(0,1);
    TimeCenter_min = zeros(0,1);
    Comparison = strings(0,1);
    N_Group1 = zeros(0,1);
    N_Group2 = zeros(0,1);
    P_raw = zeros(0,1);
    P_HolmWithinBin = zeros(0,1);

    pairs = [1 2; 1 3; 2 3];

    bins = categories(D.TimeBin);

    for b = 1:numel(bins)

        Db = D(string(D.TimeBin) == string(bins{b}),:);

        raw = nan(3,1);
        n1 = zeros(3,1);
        n2 = zeros(3,1);

        for q = 1:3

            g1 = genotypeOrder(pairs(q,1));
            g2 = genotypeOrder(pairs(q,2));

            v1 = Db.MeanX_px(string(Db.Genotype) == g1);
            v2 = Db.MeanX_px(string(Db.Genotype) == g2);

            v1 = v1(isfinite(v1));
            v2 = v2(isfinite(v2));

            n1(q) = numel(v1);
            n2(q) = numel(v2);

            if numel(v1)>=2 && numel(v2)>=2
                raw(q) = ranksum(v1,v2);
            end
        end

        adj = local_holm_adjust(raw);

        center = mean(Db.TimeCenter_min,'omitnan');

        for q = 1:3

            Bin(end+1,1) = string(bins{b}); %#ok<AGROW>
            TimeCenter_min(end+1,1) = center; %#ok<AGROW>

            Comparison(end+1,1) = ...
                genotypeOrder(pairs(q,1)) + " vs " + ...
                genotypeOrder(pairs(q,2)); %#ok<AGROW>

            N_Group1(end+1,1) = n1(q); %#ok<AGROW>
            N_Group2(end+1,1) = n2(q); %#ok<AGROW>
            P_raw(end+1,1) = raw(q); %#ok<AGROW>
            P_HolmWithinBin(end+1,1) = adj(q); %#ok<AGROW>
        end
    end

    binStats = table( ...
        Bin,TimeCenter_min,Comparison,N_Group1,N_Group2, ...
        P_raw,P_HolmWithinBin, ...
        'VariableNames',{ ...
        'TimeBin','TimeCenter_min','Comparison', ...
        'N_Group1_plates','N_Group2_plates', ...
        'P_raw','P_HolmWithinBin'});
end


function adjustedP = local_holm_adjust(rawP)

    rawP = rawP(:);
    adjustedP = nan(size(rawP));

    good = isfinite(rawP);
    p = rawP(good);

    if isempty(p)
        return
    end

    [ps,ord] = sort(p);
    m = numel(ps);

    adjSorted = nan(m,1);
    running = 0;

    for i = 1:m

        this = (m-i+1)*ps(i);
        running = max(running,this);
        adjSorted(i) = min(running,1);
    end

    tmp = nan(m,1);
    tmp(ord) = adjSorted;

    adjustedP(good) = tmp;
end


function C = local_track_palette(key,nTracks,baseColor)

    if nTracks <= 0
        C = zeros(0,3);
        return
    end

    key = lower(string(key));

    if key == "n2"

        c0 = [0.05 0.05 0.05];
        c1 = [0.72 0.72 0.72];

    elseif contains(key,"eat")

        c0 = [0.00 0.35 0.10];
        c1 = [0.68 0.86 0.68];

    elseif contains(key,"unc")

        c0 = [0.92 0.67 0.88];
        c1 = [0.55 0.00 0.43];

    else

        c0 = max(baseColor*0.55,0);
        c1 = 1-(1-baseColor)*0.35;
    end

    a = linspace(0,1,nTracks)';
    C = (1-a).*c0 + a.*c1;
end
