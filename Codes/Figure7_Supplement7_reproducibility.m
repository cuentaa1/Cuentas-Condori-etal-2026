% NOT GENERATED
% -------------
% Figure 7A is a schematic and is not calculated from tracking data.
%
% Supplement 7C ("Left" versus "Stayed") is NOT generated by the supplied
% analysis source because that source does not define the behavioral rule
% used to classify an animal as "Left" versus "Stayed". That panel should be
% added only after the exact classification rule and statistical test are
% documented; this script intentionally does not infer that rule from track
% endings.
%
% ASSAY GEOMETRY
% --------------
% Physical arena:
%   X = 900 px  -> left edge
%   X = 1800 px -> right edge
%
% Before gradient switch (0-15 min):
%   900 px = 15 C
%   1800 px = 25 C
%
% Gradient inversion:
%   begins at 15 min
%   completed by ~18 min
%
% After switch (18-30 min):
%   900 px = 23 C
%   1800 px = 17 C
%
% IMPORTANT:
% Physical X position is the underlying coordinate for all trajectory and
% mean-position plots. Therefore, an animal at the same physical location
% does not jump horizontally when the temperature gradient is inverted.
%
% Each assay plate is treated as an independent biological replicate.
% =========================================================================

