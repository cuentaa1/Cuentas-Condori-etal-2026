% Recording / assay.
fps = 2;
assay_duration_min = 30;

% Fixed physical arena.
x_left_px  = 900;
x_right_px = 1800;

% Thermal calibration before inversion.
pre_left_C  = 15;
pre_right_C = 25;

% Thermal calibration after inversion.
post_left_C  = 23;
post_right_C = 17;

% Switch timing.
switch_start_min = 15;
switch_end_min   = 18;

% Histogram windows.
hist_window_min = 3;

% Number of bins across the fixed physical arena.
n_hist_bins = 40;

% Plot trajectory points at 1 Hz for display only.
% The underlying data remain at 2 fps.
plot_every_n_frames = 2;

% Plot time from top to bottom, matching the manuscript panels.
time_increases_downward = true;

% Colors used in the manuscript.
color_WT    = [0.00 0.00 0.00];
color_eat4  = [0.00 0.55 0.20];
color_unc17 = [0.80 0.00 0.65];

% Pale thermal-background colors.
cold_rgb = [0.68 0.91 0.98];
warm_rgb = [1.00 0.72 0.52];

datasets = struct( ...
    'key',   {"N2","eat4","unc17"}, ...
    'label', {"wild type","eat-4 cKO","unc-17 cKO"}, ...
    'Xfile', {"X_N2.mat","X_eat4.mat","X_unc17.mat"}, ...
    'Yfile', {"Y_N2.mat","Y_eat4.mat","Y_unc17.mat"}, ...
    'Pfile', {"plate_N2.mat","plate_eat4.mat","plate_unc17.mat"}, ...
    'color', {color_WT,color_eat4,color_unc17});

nGroups = numel(datasets);

%% ========================================================================
% LOAD TRAJECTORIES
% ========================================================================

nFramesRequested = round(assay_duration_min*60*fps);
full_time_min = (0:nFramesRequested-1)'/(fps*60);

results = repmat(struct(),nGroups,1);

for g = 1:nGroups

    key = string(datasets(g).key);

    [X,Y,plate] = local_load_xy_plate( ...
        fullfile(data_dir,datasets(g).Xfile), ...
        fullfile(data_dir,datasets(g).Yfile), ...
        fullfile(data_dir,datasets(g).Pfile), ...
        key);

    nUse = min([size(X,1),size(Y,1),nFramesRequested]);

    X = X(1:nUse,:);
    Y = Y(1:nUse,:);
    t = full_time_min(1:nUse);

    if numel(plate) ~= size(X,2)
        error('%s: plate vector length does not match number of tracks.', ...
            datasets(g).label);
    end

    % A valid spatial observation requires both coordinates.
    validXY = isfinite(X) & isfinite(Y);

    X(~validXY) = NaN;
    Y(~validXY) = NaN;

    results(g).key = key;
    results(g).label = string(datasets(g).label);
    results(g).color = datasets(g).color;
    results(g).X = X;
    results(g).Y = Y;
    results(g).validXY = validXY;
    results(g).time_min = t;
    results(g).plate = string(plate(:));
end

%% ========================================================================
% SUPPLEMENT 7A
% INSTANTANEOUS POSITION HISTOGRAMS IN CONSECUTIVE 3-MIN WINDOWS
% ========================================================================
% Every valid instantaneous animal position within each 3-min interval is
% included. These histograms are descriptive and do not treat video frames
% from the same animal as independent biological replicates.
%
% Histogram bars are calculated in PHYSICAL X coordinates. Temperature is
% used only to label the fixed physical axis:
%
%   before 15 min: 15 -> 25 C
%   15-18 min:     physical X pixels, because the gradient is transitioning
%   after 18 min:  23 -> 17 C

hist_edges_min = 0:hist_window_min:assay_duration_min;
nWindows = numel(hist_edges_min)-1;

x_hist_edges = linspace(x_left_px,x_right_px,n_hist_bins+1);

hist_source = table();

for g = 1:nGroups

    X = results(g).X;
    t = results(g).time_min;
    plate = results(g).plate;

    for w = 1:nWindows

        t0 = hist_edges_min(w);
        t1 = hist_edges_min(w+1);

        if w < nWindows
            frameMask = t >= t0 & t < t1;
        else
            frameMask = t >= t0 & t <= t1;
        end

        Xw = X(frameMask,:);
        [frameInWindow,trackIdx] = find(isfinite(Xw));

        if isempty(frameInWindow)
            continue
        end

        absoluteFrames = find(frameMask);
        absoluteFrames = absoluteFrames(frameInWindow);

        xVals = Xw(sub2ind(size(Xw),frameInWindow,trackIdx));

        Tnew = table( ...
            repmat(results(g).label,numel(xVals),1), ...
            string(plate(trackIdx)), ...
            trackIdx, ...
            t(absoluteFrames), ...
            repmat(t0,numel(xVals),1), ...
            repmat(t1,numel(xVals),1), ...
            xVals, ...
            'VariableNames',{ ...
            'Genotype','Plate','TrackID','Time_min', ...
            'WindowStart_min','WindowEnd_min','X_px'});

        hist_source = [hist_source; Tnew]; %#ok<AGROW>
    end
end

writetable(hist_source, ...
    fullfile(output_dir,"Supplement7A_instantaneous_position_source_data.csv"));

figHist = figure( ...
    'Color','w', ...
    'Position',[100 50 650 1200], ...
    'Name','Supplement 7A instantaneous positions');

tlHist = tiledlayout(figHist,nWindows,1, ...
    'TileSpacing','compact', ...
    'Padding','compact');

for w = 1:nWindows

    ax = nexttile(tlHist,w);
    hold(ax,'on');

    t0 = hist_edges_min(w);
    t1 = hist_edges_min(w+1);

    for g = 1:nGroups

        rows = ...
            hist_source.Genotype == results(g).label & ...
            hist_source.WindowStart_min == t0 & ...
            hist_source.WindowEnd_min == t1;

        vals = hist_source.X_px(rows);
        vals = vals(isfinite(vals));

        if isempty(vals)
