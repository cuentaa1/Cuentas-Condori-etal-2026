    plate = results(g).plate;

    plateIDs = unique(plate,'stable');
    plateMeanX = nan(numel(t),numel(plateIDs));

    for p = 1:numel(plateIDs)

        idx = plate == plateIDs(p);

        % One plate mean at every time point.
        plateMeanX(:,p) = mean(X(:,idx),2,'omitnan');

        good = isfinite(plateMeanX(:,p));

        if any(good)
            Tcurve = table( ...
                repmat(results(g).label,sum(good),1), ...
                repmat(plateIDs(p),sum(good),1), ...
                t(good), ...
                plateMeanX(good,p), ...
                'VariableNames',{ ...
                'Genotype','Plate','Time_min','MeanX_px'});

            plate_curve_source = [plate_curve_source; Tcurve]; %#ok<AGROW>
        end

        % Plate-level 3-min means for statistical analysis.
        for w = 1:nWindows

            t0 = hist_edges_min(w);
            t1 = hist_edges_min(w+1);

            if w < nWindows
                frameMask = t >= t0 & t < t1;
            else
                frameMask = t >= t0 & t <= t1;
            end

            value = mean(plateMeanX(frameMask,p),'omitnan');

            if ~isfinite(value)
                continue
            end

            plateUID = results(g).label + "_" + plateIDs(p);
            binLabel = sprintf('%02d-%02d',t0,t1);

            Tbin = table( ...
                results(g).label, ...
                plateIDs(p), ...
                plateUID, ...
                string(binLabel), ...
                t0,t1,(t0+t1)/2,value, ...
                'VariableNames',{ ...
                'Genotype','Plate','PlateUID','TimeBin', ...
                'WindowStart_min','WindowEnd_min','TimeCenter_min', ...
                'MeanX_px'});

            plate_bin_source = [plate_bin_source; Tbin]; %#ok<AGROW>
        end
    end

    mu = mean(plateMeanX,2,'omitnan');

    n = sum(isfinite(plateMeanX),2);
    sem = std(plateMeanX,0,2,'omitnan')./sqrt(n);
    sem(n<2) = NaN;

    fill(ax, ...
        [mu-sem; flipud(mu+sem)], ...
        [t; flipud(t)], ...
        results(g).color, ...
        'FaceAlpha',0.12, ...
        'EdgeColor','none', ...
        'HandleVisibility','off');

    plot(ax,mu,t, ...
        'Color',results(g).color, ...
        'LineWidth',2.0, ...
        'DisplayName',results(g).label);
end

